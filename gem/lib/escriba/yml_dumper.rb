# frozen_string_literal: true

require "yaml"
require "pathname"
require_relative "yml_format"

module Escriba
  # Writes the translation catalog: one config/locales/escriba.<locale>.yml per
  # translated locale (every available locale but the dev locale), holding
  # exactly the strings static extraction finds in the source.
  #
  # The files are the source of truth for translations, so a dump never loses
  # a value: every entry keeps what the file already says. New strings appear
  # as blank skeleton entries, and strings no longer in the source are dropped.
  # Each entry is annotated with its source copy (and meaning) as a comment, so
  # a person or an LLM can fill in the blanks from the file alone. A plural gets
  # a slot for every form the source writes and every form its locale uses
  # (Escriba.plural_forms): English source writes one/other, Polish also needs
  # few and many.
  class YmlDumper
    PLURAL_FORM_ORDER = KeyDeriver::PLURAL_FORM_KEYS.map(&:to_s).freeze
    HEADER = <<~HEADER
      # Generated by `bin/rails escriba:dump_yml`; edit the values, not the keys.
      # A blank entry is untranslated and shows the source copy until filled in.
    HEADER

    # extracted: the SourceExtractor::ExtractedString entries; they are the
    # catalog.
    def initialize(dir:, extracted:)
      @dir = Pathname.new(dir)
      @extracted = extracted
    end

    # The files the dump writes, one per translated locale.
    def paths
      locales.map { |locale| @dir.join(YmlFormat.file_name(locale)) }
    end

    # What the dump writes, without writing it: { path => file content }.
    def contents
      existing = read_existing
      paths.zip(locales).to_h { |path, locale| [path, file_content(locale, existing[locale.to_s] || {})] }
    end

    # Dump files that #dump! would delete: those of locales no longer
    # translated.
    def stale_files
      current = paths.map(&:to_s)
      dump_files.reject { |file| current.include?(file) }
    end

    # Writes every file, deletes stale ones, and returns the written paths.
    def dump!
      files = contents
      stale_files.each { |stale| File.delete(stale) }
      @dir.mkpath
      files.each { |path, content| File.write(path, content, encoding: Encoding::UTF_8) }
      files.keys
    end

    private

    def locales
      Escriba.translated_locales
    end

    def catalog
      @catalog ||= @extracted.sort_by { |entry| [Escriba.source_text(entry), entry.meaning.to_s, entry.key] }
    end

    def dump_files
      Dir[@dir.join(YmlFormat::FILE_GLOB).to_s].sort
    end

    def read_existing
      dump_files.to_h { |file| [YmlFormat.locale_of(file), YmlFormat.entries(file)] }
    end

    def file_content(locale, existing)
      lines = [HEADER.chomp, "#{locale}:"]
      if catalog.empty?
        lines << "  #{YmlFormat::NAMESPACE}: {}"
      else
        lines << "  #{YmlFormat::NAMESPACE}:"
        forms = Escriba.plural_forms(locale) || []
        catalog.each { |entry| lines.concat(entry_lines(entry, existing[entry.key], forms)) }
      end
      lines.join("\n") + "\n"
    end

    def entry_lines(entry, existing_value, locale_forms)
      indent = " " * 4
      comment_lines(entry, indent) + value_lines(entry, existing_value, locale_forms, indent)
    end

    def comment_lines(entry, indent)
      lines = Escriba.source_text(entry).split("\n").map { |line| "#{indent}# #{line}" }
      lines << "#{indent}# meaning: #{entry.meaning}" if entry.meaning && !entry.meaning.empty?
      lines
    end

    def value_lines(entry, existing_value, locale_forms, indent)
      value = blank_value?(existing_value) ? skeleton(entry) : existing_value
      value = ordered_forms(with_locale_forms(value, locale_forms)) if value.is_a?(Hash)

      # Serializing each entry through Psych keeps quoting/escaping correct;
      # re-indenting every line by the same amount preserves validity.
      YAML.dump({ entry.key => value }).sub(/\A---\n/, "").chomp.split("\n").map { |line| "#{indent}#{line}" }
    end

    def skeleton(entry)
      if entry.plural && entry.source_copy.is_a?(Hash)
        entry.source_copy.keys.to_h { |form| [form.to_s, ""] }
      else
        ""
      end
    end

    # Adds a blank slot for each form the locale uses that the value lacks,
    # keeping the values already there.
    def with_locale_forms(forms, locale_forms)
      locale_forms.to_h { |form| [form, ""] }.merge(forms.transform_keys(&:to_s))
    end

    def blank_value?(value)
      if value.is_a?(Hash)
        value.values.all? { |v| v.to_s.strip.empty? }
      else
        value.to_s.strip.empty?
      end
    end

    def ordered_forms(forms)
      forms
        .transform_keys(&:to_s)
        .sort_by { |form, _| PLURAL_FORM_ORDER.index(form) || PLURAL_FORM_ORDER.size }
        .to_h
    end
  end
end
